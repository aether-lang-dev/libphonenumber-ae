#!/usr/bin/env bash
# generate_metadata.sh — regenerate the engine's metadata tables from the
# pristine in-tree resources/. These .ae tables are BUILD ARTIFACTS (gitignored),
# derived from Google's XML/txt; this script is run before any `ae build` that
# imports them (the .build.ae nodes and bootstrap.sh call it).
#
# Usage:
#   core/gen/generate_metadata.sh [LANGS...]
#     LANGS  carrier/geocoder languages to generate (default: en). English is
#            always generated (it's the default the dispatcher falls back to).
#
# Produces under core/:
#   metadata.ae               (phone metadata — always)
#   shortnumber_metadata.ae   (always)
#   timezone_metadata.ae      (always)
#   altformats_metadata.ae    (alternate formats, matcher grouping — always)
#   carrier_metadata_<lang>.ae, geocoder_metadata_<lang>.ae  (per language)
#   carrier_blobs.ae, geocoder_blobs.ae  (dispatchers over the built languages)
set -euo pipefail

HERE="$(cd "$(dirname "$0")/../.." && pwd)"   # repo root
cd "$HERE"
CORE="core"
GEN="core/gen"

# ae must be on PATH
command -v ae >/dev/null 2>&1 || { echo "generate_metadata: 'ae' not on PATH" >&2; exit 1; }

# languages: en always, plus any requested (dedup, en first)
langs=(en)
for l in "$@"; do
    [ "$l" = "en" ] && continue
    langs+=("$l")
done

say() { printf 'gen-metadata: %s\n' "$*"; }

# --- always-on, language-free tables (ae run, no argv needed) ---
say "phone metadata"
ae run "$GEN/generate.ae"        > "$CORE/metadata.ae"
say "short-number metadata"
ae run "$GEN/generate_short.ae"  > "$CORE/shortnumber_metadata.ae"
say "timezone metadata"
ae run "$GEN/generate_tz.ae"     > "$CORE/timezone_metadata.ae"
say "alternate-formats metadata"
ae run "$GEN/generate_altformats.ae" > "$CORE/altformats_metadata.ae"

# --- per-language carrier + geocoder (need argv -> compile the generator once) ---
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
ae build "$GEN/generate_carrier.ae" -o "$tmp/gc"
ae build "$GEN/generate_geo.ae"     -o "$tmp/gg"

for l in "${langs[@]}"; do
    say "carrier[$l]"
    "$tmp/gc" "$l" > "$CORE/carrier_metadata_$l.ae"
    say "geocoder[$l]"
    "$tmp/gg" "$l" > "$CORE/geocoder_metadata_$l.ae"
done

# --- dispatchers: import the built languages, route blob_for_lang(lang) ---
gen_dispatch() {
    local kind="$1" out="$2"   # kind = carrier | geocoder
    {
        echo "// core.${kind}_blobs — GENERATED by core/gen/generate_metadata.sh."
        echo "// Routes blob_for_lang(lang) to the ${kind} metadata compiled into this"
        echo "// build (languages: ${langs[*]}); unknown/absent languages fall back to en."
        echo ""
        for l in "${langs[@]}"; do echo "import ${kind}_metadata_$l"; done
        echo ""
        echo "exports(blob_for_lang)"
        echo ""
        echo "blob_for_lang(lang: string) -> string {"
        for l in "${langs[@]}"; do
            [ "$l" = "en" ] && continue
            echo "    if lang == \"$l\" { return ${kind}_metadata_$l.blob() }"
        done
        echo "    return ${kind}_metadata_en.blob()"
        echo "}"
    } > "$out"
}
say "carrier dispatcher (${langs[*]})"
gen_dispatch carrier  "$CORE/carrier_blobs.ae"
say "geocoder dispatcher (${langs[*]})"
gen_dispatch geocoder "$CORE/geocoder_blobs.ae"

say "done (languages: ${langs[*]})"

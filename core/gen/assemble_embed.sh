#!/usr/bin/env bash
# assemble_embed.sh — compose a variant embed .ae from the base + selected
# feature fragments, so a consumer builds a .so with ONLY the features (and
# their embedded metadata blobs) they want.
#
# Why this exists: the engine's side-libraries bake large data tables into the
# .so (the geocoder blob alone is ~7 MB). A validation-only build is ~200 KB;
# the full build is ~8.4 MB. `ae build --emit=lib` compiles ONE physical source
# module and does not emit re-exported imports, so each variant .so must contain
# its own pn_embed_* definitions in one file. This script is that assembly step
# (the standard Aether compile-time-variant idiom: select the source, don't ask
# the compiler for conditional compilation).
#
# Usage:
#   core/gen/assemble_embed.sh OUT.ae [feature ...]
# Features (any subset, in any order): short tz carrier geo
#   (no features -> validation-only base)
#   'all' -> short tz carrier geo
#
# Examples:
#   core/gen/assemble_embed.sh core/embed.ae                 # validation only
#   core/gen/assemble_embed.sh core/embed_geo.ae geo         # validation + geocoder
#   core/gen/assemble_embed.sh core/embed_full.ae all        # everything
#
# LANGUAGE selection is a SEPARATE, orthogonal axis handled by
# core/gen/generate_metadata.sh <langs...>: it picks which carrier/geocoder
# languages get compiled in (English is always the default/fallback). So a
# consumer chooses features here and languages there. Run generate_metadata.sh
# BEFORE assembling/building, e.g.:
#   core/gen/generate_metadata.sh en de fr    # metadata for en+de+fr
#   core/gen/assemble_embed.sh core/embed_geo.ae geo
#   ae build --emit=lib core/embed_geo.ae --extra core/_embed_support.c -o out.so
#   # -> the .so answers geo_description(region,input,"de") etc.
#
# Then build:
#   ae build --emit=lib core/embed_geo.ae --extra core/_embed_support.c \
#       -o core/native/libphonenumber_ae.so
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"   # core/
FRAG="$HERE/embed"

out="${1:?usage: assemble_embed.sh OUT.ae [short tz carrier geo | all]}"
shift || true

feats=("$@")
if [ "${#feats[@]}" -eq 1 ] && [ "${feats[0]}" = "all" ]; then
    feats=(short tz carrier geo)
fi

# validate feature names
for f in "${feats[@]:-}"; do
    case "$f" in
        short|tz|carrier|geo) ;;
        "") ;;
        *) echo "assemble_embed: unknown feature '$f' (want: short tz carrier geo | all)" >&2; exit 2 ;;
    esac
done

tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
{
    echo "// GENERATED by core/gen/assemble_embed.sh — do not edit."
    echo "// Variant: base${feats:+ + }$(IFS=' '; echo "${feats[*]:-}")"
    echo "//"
    echo "// A consumer builds this with:"
    echo "//   ae build --emit=lib <this file> --extra core/_embed_support.c -o <out>.so"
    echo ""
    cat "$FRAG/base.ae.frag"
    for f in "${feats[@]:-}"; do
        [ -n "$f" ] || continue
        echo ""
        cat "$FRAG/$f.ae.frag"
    done
} > "$tmp"

mv "$tmp" "$out"
trap - EXIT
echo "assemble_embed: wrote $out (base${feats:+ + }$(IFS=' '; echo "${feats[*]:-}"))"
